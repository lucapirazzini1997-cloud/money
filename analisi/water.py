import sys, numpy as np
sys.path.insert(0,str(__import__('pathlib').Path(__file__).resolve().parent.parent/'strumenti_rom'))
import romlib
R=romlib.Rom(sys.argv[1])
WATER_B={0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f,0x20,0x21,0x22,0x23,0x24,0x25,0x26,0x27,0x28,0x29,0x2a,0x2b,0x2c,0x2d,0x2e,0x2f,0x30,0x31,0x32,0x33,0x34,0x35,0x36,0x37,0x38,0x39,0x3a,0x3b,0x3c,0x3d,0x3e,0x3f}
SURF_B={0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1a,0x1b}
for key in sys.argv[2:]:
    g,n=map(int,key.split('.'))
    m=R.map(g,n); bl=R.blocks(m); mt=R.renderer(m)
    sus=[]
    for y in range(m['height']):
        for x in range(m['width']):
            v=int(bl[y,x]); i=v&1023; coll=(v>>10)&3
            img=mt(i).astype(int); r,gg,b=img[...,0].mean(),img[...,1].mean(),img[...,2].mean()
            blue = b>gg+25 and b>r+60
            beh=R.attr(m,i)&0xff
            if blue and coll==0 and beh not in SURF_B and beh not in (0x15,):
                sus.append((x,y,i,hex(beh)))
    print(key,len(sus),sus[:40])
